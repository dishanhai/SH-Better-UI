#!/usr/bin/env python3
"""Generate the built-in visual icon reference from checked-in texture and SVG files."""

import argparse
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parent.parent
ARTWORK = ROOT / "artwork" / "visual-icons"
TEXTURES = ROOT / "src" / "main" / "resources" / "assets" / "sh_better_ui" / "textures" / "gui"
NAME_FILE = ARTWORK / "icon-names.zh-TW.tsv"
CATALOG = ARTWORK / "CATALOG.zh-TW.md"
ID = re.compile(r"[a-z0-9_]+")


def indexed_files(directory, suffix):
    result = {path.stem: path for path in directory.glob(f"*{suffix}") if path.is_file()}
    for name in result:
        if not ID.fullmatch(name):
            raise ValueError(f"Invalid visual icon ID: {name!r}")
    return result


def chinese_names():
    lines = NAME_FILE.read_text(encoding="utf-8").splitlines()
    if not lines or lines[0] != "圖示 ID\t中文名稱":
        raise ValueError("Invalid icon name TSV header")
    names = {}
    for number, line in enumerate(lines[1:], start=2):
        parts = line.split("\t")
        if len(parts) != 2 or not ID.fullmatch(parts[0]) or not parts[1].strip():
            raise ValueError(f"Invalid icon name TSV line {number}")
        name, label = parts
        if name in names:
            raise ValueError(f"Duplicate icon name TSV ID: {name}")
        names[name] = label.strip()
    return names


def require_matching(label, actual, expected):
    missing = sorted(expected - actual)
    extra = sorted(actual - expected)
    errors = []
    if missing:
        errors.append(f"{label} missing: " + ", ".join(missing))
    if extra:
        errors.append(f"{label} without a 16 px asset: " + ", ".join(extra))
    if errors:
        raise ValueError("\n".join(errors))


def label_cell(label):
    return (label.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
                 .replace("|", "&#124;").replace("`", "&#96;").replace("[", "&#91;").replace("]", "&#93;"))


def generate():
    png16 = indexed_files(TEXTURES / "display", ".png")
    png64 = indexed_files(TEXTURES / "display_64", ".png")
    masters = indexed_files(ARTWORK, ".svg")
    names = chinese_names()
    if not png16:
        raise ValueError("No built-in 16 px visual icons found")
    require_matching("64 px textures", png64.keys(), png16.keys())
    require_matching("Chinese names", names.keys(), png16.keys())
    orphans = sorted(masters.keys() - png16.keys())
    if orphans:
        raise ValueError("SVG masters without a runtime texture pair: " + ", ".join(orphans))

    lines = [
        "# 內建圖示索引",
        "",
        "<!-- Generated by scripts/generate-visual-icon-catalog.py. Do not edit by hand. -->",
        "",
        f"共 **{len(png16)}** 個圖示：**{len(masters)}** 個有 SVG 原稿，"
        f"**{len(png16) - len(masters)}** 個仍只有 PNG。",
        "",
        "以頁內搜尋（Ctrl+F／⌘F）查找中文名稱、品牌原名、圖示 ID 或 SVG 檔名。"
        "圖示 ID 是資源檔名去掉副檔名；SVG 欄點擊檔名即可開啟此目錄下的原稿。",
        "",
        "遊戲材質路徑為 `sh_better_ui:textures/gui/display/<圖示 ID>.png`（16 × 16），"
        "或 `sh_better_ui:textures/gui/display_64/<圖示 ID>.png`（64 × 64）。"
        "「未遷移」只表示沒有 SVG 原稿，兩種 PNG 仍可使用。相同圖示在不同畫面可以有不同的按鈕文字。",
        "",
        "| 中文名稱 | 圖示 ID | SVG 檔名／相對路徑 | 16 × 16 PNG | 64 × 64 PNG |",
        "| --- | --- | --- | --- | --- |",
    ]
    prefix = "../../" + TEXTURES.relative_to(ROOT).as_posix()
    for name in sorted(png16):
        svg = f"[`{name}.svg`](./{name}.svg)" if name in masters else "未遷移（只有 PNG）"
        lines.append(f"| {label_cell(names[name])} | `{name}` | {svg} | "
                     f"[PNG]({prefix}/display/{name}.png) | [PNG]({prefix}/display_64/{name}.png) |")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the checked-in table is stale")
    args = parser.parse_args()
    try:
        content = generate().encode("utf-8")
    except (OSError, ValueError) as exc:
        parser.exit(1, f"{exc}\n")
    if args.check:
        if not CATALOG.is_file() or CATALOG.read_bytes() != content:
            parser.exit(1, f"Out-of-date catalog: {CATALOG.relative_to(ROOT)}\n")
    else:
        CATALOG.write_bytes(content)
    print(f"{CATALOG.relative_to(ROOT)}: {'verified' if args.check else 'generated'}")


if __name__ == "__main__":
    main()
