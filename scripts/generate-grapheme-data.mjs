// Regenerates Java tables from the Unicode 17.0.0 UCD. See docs/p9-typography.md.
import { readFile, writeFile } from 'node:fs/promises'
import { join } from 'node:path'

const directory = process.argv[2]
if (!directory) throw new Error('Usage: node scripts/generate-grapheme-data.mjs <UCD file directory>')
const source = await Promise.all([
  'GraphemeBreakProperty.txt', 'DerivedCoreProperties.txt', 'emoji-data.txt', 'GraphemeBreakTest.txt',
].map(file => readFile(join(directory, file), 'utf8')))
const [graphemes, derived, emoji, conformance] = source
if (![graphemes, derived, conformance].every(data => data.split('\n', 1)[0].includes('-17.0.0.txt'))
    || !emoji.includes('# Version: 17.0')) {
  throw new Error('Expected Unicode 17.0.0 files')
}

const grapheme = new Map([
  ['Other', 0], ['CR', 1], ['LF', 2], ['Control', 3], ['L', 4], ['V', 5], ['T', 6],
  ['LV', 7], ['LVT', 8], ['Extend', 9], ['ZWJ', 10], ['SpacingMark', 11], ['Prepend', 12],
  ['Regional_Indicator', 13],
])
const conjunct = new Map([['Consonant', 1], ['Extend', 2], ['Linker', 3]])
const properties = new Uint8Array(0x110000)
load(graphemes, ([property]) => grapheme.get(property))
load(derived, ([property, value]) => property === 'InCB' ? conjunct.get(value) * 16 : 0)
load(emoji, ([property]) => property === 'Extended_Pictographic' ? 0x40 : 0)

function load(data, select) {
  for (const line of data.split('\n')) {
    const fields = line.split('#', 1)[0].trim()
    if (!fields) continue
    const [points, ...parts] = fields.split(';').map(field => field.trim())
    const value = select(parts)
    if (!Number.isInteger(value)) throw new Error(`Unknown Unicode property in ${fields}`)
    if (!value) continue
    const [start, end = start] = points.split('..').map(point => Number.parseInt(point, 16))
    for (let point = start; point <= end; point++) properties[point] |= value
  }
}

const rows = []
for (let point = 0; point < properties.length; point++) {
  if (point === 0 || properties[point] !== properties[point - 1]) {
    rows.push(`0x${((point << 7) | properties[point]).toString(16)}`)
  }
}
const table = []
for (let index = 0; index < rows.length; index += 10) {
  table.push(`        ${rows.slice(index, index + 10).join(', ')},`)
}
const cases = conformance.split('\n')
  .map(line => line.split('#', 1)[0].trim())
  .filter(line => line.startsWith('÷'))
  .map(line => `        ${line.replaceAll('÷', '|').replaceAll('×', '+')}`)

const packagePath = 'com/dishanhai/sh_better_ui/kernel/api/richtext'
const heading = `// Generated by scripts/generate-grapheme-data.mjs. Do not edit.
// Derived from Unicode 17.0.0 data, © 2025 Unicode, Inc.
// SPDX-License-Identifier: Unicode-3.0
// License: src/main/resources/META-INF/third-party/unicode/LICENSE
package ${packagePath.replaceAll('/', '.')};

`

await Promise.all([
  writeFile(new URL(`../src/kernel/java/${packagePath}/UnicodeGraphemeData.java`, import.meta.url),
    heading + `import java.util.Arrays;

final class UnicodeGraphemeData {
    // Each entry packs the first code point of a range and its seven property bits.
    private static final int[] RANGES = {
${table.join('\n')}
    };

    private UnicodeGraphemeData() {}

    static int properties(int codePoint) {
        int index = Arrays.binarySearch(RANGES, (codePoint << 7) | 0x7F);
        return RANGES[index >= 0 ? index : -index - 2] & 0x7F;
    }
}
`),
  writeFile(new URL(`../src/kernelTest/java/${packagePath}/UnicodeGraphemeTestData.java`, import.meta.url),
    heading + `final class UnicodeGraphemeTestData {
    static final String CASES = """
${cases.join('\n')}
        """;

    private UnicodeGraphemeTestData() {}
}
`),
])
